package main

import (
	"context"
	"crypto/rsa"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"math/big"
	"net/http"
	"strings"
	"sync"
	"time"

	"github.com/golang-jwt/jwt/v5"
)

type AccessClaims struct {
	ClientID  string `json:"client_id"`
	Scope     string `json:"scope"`
	SessionID string `json:"sid"`
	jwt.RegisteredClaims
}

type JWTVerifier struct {
	client      *http.Client
	logger      *slog.Logger
	jwksURL     string
	issuer      string
	audience    string
	mu          sync.RWMutex
	keys        map[string]*rsa.PublicKey
	refreshMu   sync.Mutex
	lastRefresh time.Time
}

type jwksDocument struct {
	Keys []jwk `json:"keys"`
}

type jwk struct {
	KeyType string `json:"kty"`
	Use     string `json:"use"`
	Alg     string `json:"alg"`
	KeyID   string `json:"kid"`
	N       string `json:"n"`
	E       string `json:"e"`
}

func NewJWTVerifier(ctx context.Context, jwksURL, issuer, audience string, logger *slog.Logger) (*JWTVerifier, error) {
	if jwksURL == "" || issuer == "" || audience == "" {
		return nil, errors.New("JWKS URL, issuer, and audience are required")
	}
	v := &JWTVerifier{
		client:   &http.Client{Timeout: 3 * time.Second},
		logger:   logger,
		jwksURL:  jwksURL,
		issuer:   issuer,
		audience: audience,
		keys:     make(map[string]*rsa.PublicKey),
	}
	if err := v.Refresh(ctx, "startup"); err != nil {
		return nil, err
	}
	return v, nil
}

func (v *JWTVerifier) Verify(ctx context.Context, rawToken, correlationID string) (*AccessClaims, error) {
	claims := &AccessClaims{}
	parsed, err := jwt.ParseWithClaims(rawToken, claims, func(t *jwt.Token) (any, error) {
		if t.Method.Alg() != jwt.SigningMethodRS256.Alg() {
			return nil, fmt.Errorf("unexpected signing algorithm %q", t.Method.Alg())
		}
		if typ, _ := t.Header["typ"].(string); typ != "at+jwt" && typ != "application/at+jwt" {
			return nil, errors.New("unexpected JWT type")
		}
		kid, _ := t.Header["kid"].(string)
		if kid == "" {
			return nil, errors.New("JWT key ID is required")
		}
		key := v.key(kid)
		if key == nil {
			if err := v.refreshForUnknownKey(ctx, kid, correlationID); err != nil {
				return nil, fmt.Errorf("refresh JWKS: %w", err)
			}
			key = v.key(kid)
		}
		if key == nil {
			return nil, fmt.Errorf("unknown JWT key ID %q", kid)
		}
		return key, nil
	},
		jwt.WithValidMethods([]string{jwt.SigningMethodRS256.Alg()}),
		jwt.WithIssuer(v.issuer),
		jwt.WithAudience(v.audience),
		jwt.WithExpirationRequired(),
	)
	if err != nil || !parsed.Valid {
		return nil, fmt.Errorf("validate JWT: %w", err)
	}
	if claims.ClientID == "" || claims.Subject == "" || claims.ClientID != claims.Subject || claims.ID == "" || claims.SessionID == "" {
		return nil, errors.New("JWT identity claims are incomplete")
	}
	return claims, nil
}

func (v *JWTVerifier) Refresh(ctx context.Context, correlationID string) error {
	v.refreshMu.Lock()
	defer v.refreshMu.Unlock()
	return v.refreshLocked(ctx, correlationID)
}

func (v *JWTVerifier) refreshForUnknownKey(ctx context.Context, keyID, correlationID string) error {
	v.refreshMu.Lock()
	defer v.refreshMu.Unlock()
	if v.key(keyID) != nil {
		return nil
	}
	// An attacker controls kid. Bound JWKS network traffic generated by random
	// unknown values while still allowing normal key rotation within seconds.
	if !v.lastRefresh.IsZero() && time.Since(v.lastRefresh) < 5*time.Second {
		return nil
	}
	return v.refreshLocked(ctx, correlationID)
}

func (v *JWTVerifier) refreshLocked(ctx context.Context, correlationID string) error {
	v.lastRefresh = time.Now()
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, v.jwksURL, nil)
	if err != nil {
		return err
	}
	request.Header.Set("X-Correlation-ID", correlationID)
	started := time.Now()
	response, err := v.client.Do(request)
	if err != nil {
		v.logger.Error("jwks_refresh_failed", "error", err, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
		return err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		err := fmt.Errorf("JWKS endpoint returned HTTP %d", response.StatusCode)
		v.logger.Error("jwks_refresh_failed", "error", err, "status", response.StatusCode, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
		return err
	}
	var document jwksDocument
	decoder := json.NewDecoder(io.LimitReader(response.Body, 1<<20))
	if err := decoder.Decode(&document); err != nil {
		err = fmt.Errorf("decode JWKS: %w", err)
		v.logger.Error("jwks_refresh_failed", "error", err, "status", response.StatusCode, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
		return err
	}
	keys := make(map[string]*rsa.PublicKey, len(document.Keys))
	for _, value := range document.Keys {
		if value.KeyType != "RSA" || value.Alg != "RS256" || value.KeyID == "" || (value.Use != "" && value.Use != "sig") {
			continue
		}
		key, err := rsaPublicKey(value.N, value.E)
		if err != nil {
			err = fmt.Errorf("decode JWKS key %q: %w", value.KeyID, err)
			v.logger.Error("jwks_refresh_failed", "error", err, "status", response.StatusCode, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
			return err
		}
		keys[value.KeyID] = key
	}
	if len(keys) == 0 {
		err := errors.New("JWKS contains no usable RS256 signing keys")
		v.logger.Error("jwks_refresh_failed", "error", err, "status", response.StatusCode, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
		return err
	}
	v.mu.Lock()
	v.keys = keys
	v.mu.Unlock()
	v.logger.Info("jwks_refresh_done", "key_count", len(keys), "status", response.StatusCode, "correlation_id", correlationID, "latency_ms", time.Since(started).Milliseconds())
	return nil
}

func (v *JWTVerifier) key(keyID string) *rsa.PublicKey {
	v.mu.RLock()
	defer v.mu.RUnlock()
	return v.keys[keyID]
}

func rsaPublicKey(encodedN, encodedE string) (*rsa.PublicKey, error) {
	nBytes, err := base64.RawURLEncoding.DecodeString(encodedN)
	if err != nil || len(nBytes) == 0 {
		return nil, errors.New("invalid RSA modulus")
	}
	eBytes, err := base64.RawURLEncoding.DecodeString(encodedE)
	if err != nil || len(eBytes) == 0 || len(eBytes) > 4 {
		return nil, errors.New("invalid RSA exponent")
	}
	e := 0
	for _, value := range eBytes {
		e = e<<8 + int(value)
	}
	if e < 3 {
		return nil, errors.New("invalid RSA exponent")
	}
	n := new(big.Int).SetBytes(nBytes)
	if n.BitLen() < 2048 {
		return nil, errors.New("RSA modulus must be at least 2048 bits")
	}
	return &rsa.PublicKey{N: n, E: e}, nil
}

func hasScope(rawScopes, expected string) bool {
	for _, scope := range strings.Fields(rawScopes) {
		if scope == expected {
			return true
		}
	}
	return false
}
